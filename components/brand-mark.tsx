export interface BrandMarkProps {
  /** Délka hrany čtverce. */
  size?: number;
  /**
   * `badge`      značka na zaobleném štítku,
   * `mark`       jen značka, průhledné pozadí, v bezpečné zóně ikony,
   * `monochrome` celá značka bílá — Android si ji odbarví sám.
   */
  variant?: "badge" | "mark" | "monochrome";
}

/** Značka SCS2 jako vektor. Kreslí se vždy ve viewBoxu 0 0 1024 1024. */
export function BrandMark({ size = 48, variant = "badge" }: BrandMarkProps) {
  const monochrome = variant === "monochrome";
  const withBadge = variant !== "mark";
  const withGlows = withBadge && !monochrome;
  const scale = variant === "mark" ? FOREGROUND_SCALE : BADGE_SCALE;

  const ink = monochrome ? COLORS.monochrome : null;
  // `useId` dává v Reactu 18+ řetězec se znaky, které nejdou do CSS selektoru.
  const uid = useId().replace(/[^a-zA-Z0-9_-]/g, "");
  const badgeFillId = `${uid}-badge-fill`;
  const glowIds = GLOWS.map((glow) => `${uid}-glow-${glow.key}`);
  const ribbonId = `${uid}-ribbon`;
  const badgeClipId = `${uid}-badge-clip`;

  return (
    <Svg width={size} height={size} viewBox={`0 0 ${CANVAS} ${CANVAS}`}>
      <Defs>
        {withGlows ? (
          <LinearGradient id={badgeFillId} x1="0" y1="0" x2="1" y2="1">
            <Stop offset="0" stopColor={COLORS.badgeFrom} />
            <Stop offset="1" stopColor={COLORS.badgeTo} />
          </LinearGradient>
        ) : null}

        {withGlows
          ? GLOWS.map((glow, index) => (
              <RadialGradient
                key={glow.key}
                id={glowIds[index]}
                gradientUnits="userSpaceOnUse"
                cx={glow.cx}
                cy={glow.cy}
                r={glow.r}
              >
                <Stop offset="0" stopColor={glow.color} stopOpacity={glow.opacity} />
                <Stop offset="0.55" stopColor={glow.color} stopOpacity={glow.opacity / 2} />
                <Stop offset="1" stopColor={glow.color} stopOpacity={0} />
              </RadialGradient>
            ))
          : null}

        <LinearGradient id={ribbonId} gradientUnits="userSpaceOnUse" x1={AXIS.x1} y1={AXIS.y1} x2={AXIS.x2} y2={AXIS.y2}>
          <Stop offset="0" stopColor={COLORS.primary} />
          <Stop offset="0.5" stopColor={COLORS.primaryVibrant} />
          <Stop offset="1" stopColor={COLORS.secondary} />
        </LinearGradient>

        {withBadge ? (
          <ClipPath id={badgeClipId}>
            <Rect x={0} y={0} width={CANVAS} height={CANVAS} rx={BADGE_RX} />
          </ClipPath>
        ) : null}
      </Defs>

      {withBadge ? (
        <Rect
          x={0}
          y={0}
          width={CANVAS}
          height={CANVAS}
          rx={BADGE_RX}
          fill={monochrome ? COLORS.monochrome : `url(#${badgeFillId})`}
        />
      ) : null}

      {withGlows ? (
        <G clipPath={`url(#${badgeClipId})`}>
          {GLOWS.map((glow, index) => (
            <Circle key={glow.key} cx={glow.cx} cy={glow.cy} r={glow.r} fill={`url(#${glowIds[index]})`} />
          ))}
        </G>
      ) : null}

      {withBadge ? (
        <Rect
          x={RIM.inset}
          y={RIM.inset}
          width={CANVAS - RIM.width}
          height={CANVAS - RIM.width}
          rx={BADGE_RX - RIM.width}
          fill="none"
          stroke={ink ?? COLORS.primaryVibrant}
          strokeOpacity={RIM.opacity}
          strokeWidth={RIM.width}
        />
      ) : null}

      <G scale={scale} originX={CANVAS / 2} originY={CANVAS / 2}>
        <Path d={RIBBON_D} fill={ink ?? `url(#${ribbonId})`} />
        <Circle cx={NODE.cx} cy={NODE.cy} r={NODE.r} fill={ink ?? COLORS.accentWarm} />
        <Circle
          cx={NODE.cx}
          cy={NODE.cy}
          r={NODE.ringR}
          fill={ink ?? COLORS.secondary}
          fillOpacity={monochrome ? 1 : 0.55}
        />
        {SPARKS.map((spark) => (
          <Circle
            key={`${spark.cx}-${spark.cy}`}
            cx={spark.cx}
            cy={spark.cy}
            r={spark.r}
            fill={ink ?? COLORS.primaryVibrant}
            fillOpacity={monochrome ? 1 : spark.opacity}
          />
        ))}
      </G>
    </Svg>
  );
}

